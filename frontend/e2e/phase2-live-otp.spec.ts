import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('bounded real OTP browser walkthrough, comparison, contextual edits and neighborhood-only clearing', async ({ page }) => {
  test.setTimeout(120000);
  await page.route('**/tile.openstreetmap.org/**', route => route.abort());
  await page.goto('/');
  await expect(page.locator('.property-card').first()).toBeVisible();
  const contract = JSON.parse(readFileSync('../data/otp/contract-input.json', 'utf8').replace(/^\uFEFF/, ''));
  const inventory = await (await page.request.get('/api/inventory')).json();
  const neighborhoods = await (await page.request.get('/api/neighborhoods')).json();
  const nearest = inventory.properties.slice().sort((a: any, b: any) => ((a.latitude - contract.origin.latitude) ** 2 + (a.longitude - contract.origin.longitude) ** 2) - ((b.latitude - contract.origin.latitude) ** 2 + (b.longitude - contract.origin.longitude) ** 2))[0];
  const id = nearest.neighborhood_ids[0];
  const feature = neighborhoods.features.find((n: any) => String(n.id ?? n.properties.id) === id);
  const properties = inventory.properties.filter((p: any) => p.neighborhood_ids.includes(id)).sort((a: any, b: any) => a.monthly_rent_toman - b.monthly_rent_toman);
  await page.getByLabel('جست‌وجوی نام محله').fill(feature.properties.name_fa);
  await page.locator('.boundary-options').first().locator('input').first().check();
  await page.getByLabel('سقف اجارهٔ ماهانه (تومان)', { exact: true }).fill(String(properties[2].monthly_rent_toman));
  const travel = contract.travel ?? contract;
  await page.getByRole('button', { name: 'انتخاب مقصد روی نقشه', exact: true }).click();
  const map = page.locator('.leaflet-container');
  const box = await map.boundingBox();
  expect(box).not.toBeNull();
  const project = (latitude: number, longitude: number) => {
    const sin = Math.sin(latitude * Math.PI / 180), scale = 256 * 2 ** 11;
    return { x: (longitude + 180) / 360 * scale, y: (0.5 - Math.log((1 + sin) / (1 - sin)) / (4 * Math.PI)) * scale };
  };
  const center = project(35.7107, 51.3978), destination = project(travel.destination.latitude, travel.destination.longitude);
  await map.click({ position: { x: box!.width / 2 + destination.x - center.x, y: box!.height / 2 + destination.y - center.y } });
  await page.getByLabel('تاریخ سفر (میلادی)').fill(travel.date);
  await page.getByLabel('ساعت تهران').fill(travel.time.slice(0, 5));
  await page.locator('.destination-editor select').first().selectOption(travel.time_mode);
  await page.getByRole('button', { name: 'تأیید مقصد و زمان', exact: true }).click();
  await page.getByLabel('مرتب‌سازی', { exact: true }).selectOption('walk_time_asc');
  await page.getByRole('button', { name: 'جست‌وجوی خانه', exact: true }).click();
  await expect(page.locator('.search-progress')).toContainText('بررسی کامل', { timeout: 90000 });
  await expect(page.locator('.property-card')).toHaveCount(3);
  await expect(page.locator('.route-summary').first()).toContainText('مبنای برنامهٔ زمانی نامعلوم');
  await page.locator('.property-card').first().getByRole('button', { name: 'جزئیات و مسیر' }).click();
  await expect(page.getByRole('dialog')).toContainText('شروع:');
  await expect(page.getByRole('dialog')).not.toContainText('[object Object]');
  await expect(page.locator('.route-legs li').first()).toBeVisible();
  await page.screenshot({ path: 'test-results/phase-2-live-route.png', fullPage: false });
  await page.getByRole('button', { name: 'بستن پنجره' }).click();
  for (let i = 0; i < 3; i++) await page.locator('.property-card').nth(i).getByRole('button', { name: 'افزودن به مقایسه' }).click();
  await page.getByRole('button', { name: 'نمایش مقایسه', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('دقیقه');
  await page.getByRole('button', { name: 'بستن پنجره' }).click();
  await page.locator('.property-card').first().getByRole('button', { name: /^مناسب است:/ }).click();
  await expect(page.getByRole('status').filter({ hasText: 'نظر شما ثبت شد' })).toBeVisible();
  await page.locator('.text-parser > summary').click();
  await page.getByLabel('خانه‌ای که می‌خواهید را توضیح دهید').fill('پارکینگ الزامی');
  await page.getByRole('button', { name: 'بررسی متن و پیشنهاد شرط‌ها' }).click();
  await page.getByRole('button', { name: 'تأیید شرط‌های پیشنهادی' }).click();
  await expect(page.getByLabel('پارکینگ الزامی', { exact: true })).toBeChecked();
  await page.getByLabel('خانه‌ای که می‌خواهید را توضیح دهید').fill('پیاده‌روی کمتر مهم‌تر است');
  await page.getByRole('button', { name: 'بررسی متن و پیشنهاد شرط‌ها' }).click();
  await page.getByRole('button', { name: 'تأیید شرط‌های پیشنهادی' }).click();
  await page.getByRole('button', { name: 'پاک‌کردن فقط محله‌ها', exact: true }).click();
  await expect(page.locator('.boundary-options').first().locator('input:checked')).toHaveCount(0);
  await expect(page.locator('.destination-editor')).toContainText('مقصد تأییدشده');
  await expect(page.getByLabel('پارکینگ الزامی', { exact: true })).toBeChecked();
  await expect(page.getByLabel('سقف اجارهٔ ماهانه (تومان)', { exact: true })).toHaveValue(String(properties[2].monthly_rent_toman));
});
